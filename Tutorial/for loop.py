"""for loop is used to iterate over a sequence and execute the block of code multiple time
syntax:
 for variable in sequence:
     block of code"""

list=["Apple","Banana","Orange","grapes"]
for i in list:
    print(i)


for i in range(11):
    print("2*",i,"=",2*i)
else:
    print("loop is finished")

for i in "hello":
    print(i)

